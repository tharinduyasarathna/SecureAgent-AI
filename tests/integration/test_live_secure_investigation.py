
import os
from contextlib import contextmanager
from uuid import uuid4

import pytest
from openai import OpenAI
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url
from sqlalchemy.orm import Session

from apps.api.app.models import User
from apps.api.rag.models import RAGDocument, RAGChunk
from apps.api.agents.audit_service import AuditService
from apps.api.agents.secure_investigation import (
    SecureInvestigationWorkflow,
)


pytestmark = pytest.mark.asyncio


@pytest.mark.asyncio
async def test_live_secure_investigation():

    # Explicit opt-in: never run live API tests
    # accidentally during the normal test suite.
    if os.getenv("RUN_LIVE_A3") != "1":
        pytest.skip("Live A3 test not enabled")

    database_url = os.getenv("TEST_DATABASE_URL")
    api_key = os.getenv("OPENAI_API_KEY")
    model = os.getenv("OPENAI_MODEL")

    if not database_url or not api_key or not model:
        pytest.skip(
            "TEST_DATABASE_URL, OPENAI_API_KEY "
            "and OPENAI_MODEL are required"
        )

    if make_url(database_url).database != "secureagent_test":
        raise RuntimeError(
            "Live tests require secureagent_test"
        )

    engine = create_engine(
        database_url,
        pool_pre_ping=True,
    )

    try:
        with engine.connect() as connection:

            actual_database = connection.execute(
                text("SELECT current_database()")
            ).scalar_one()

            if actual_database != "secureagent_test":
                raise RuntimeError(
                    "Unsafe database connection"
                )

            connection.rollback()

            # One outer transaction ensures all test
            # records, including audit records, can
            # be rolled back after verification.
            outer_transaction = connection.begin()

            def make_session():
                return Session(
                    bind=connection,
                    expire_on_commit=False,
                    join_transaction_mode="create_savepoint",
                )

            @contextmanager
            def audit_session_factory():
                session = make_session()
                try:
                    yield session
                finally:
                    session.close()

            try:
                with make_session() as db:

                    unique = uuid4().hex

                    owner = User(
                        email=f"a3_owner_{unique}@example.com",
                        password_hash="test-only-hash",
                    )

                    other_user = User(
                        email=f"a3_other_{unique}@example.com",
                        password_hash="test-only-hash",
                    )

                    db.add_all([owner, other_user])
                    db.flush()

                    owner_id = owner.id
                    other_user_id = other_user.id

                    document = RAGDocument(
                        owner_id=owner_id,
                        filename="a3_security_incident.txt",
                    )

                    foreign_document = RAGDocument(
                        owner_id=other_user_id,
                        filename="a3_private_other_user.txt",
                    )

                    db.add_all([
                        document,
                        foreign_document,
                    ])
                    db.flush()

                    # Existing pgvector schema uses
                    # 1536-dimensional embeddings.
                    # The query embedding will be
                    # generated by the real API.
                    db.add(
                        RAGChunk(
                            document_id=document.id,
                            chunk_index=0,
                            content=(
                                "Incident SEC-A3-2026: "
                                "Multiple failed login attempts "
                                "were detected. MFA remained "
                                "enabled. Security monitoring "
                                "must remain active."
                            ),
                            embedding=[0.01] * 1536,
                        )
                    )

                    db.add(
                        RAGChunk(
                            document_id=foreign_document.id,
                            chunk_index=0,
                            content=(
                                "Private incident belonging "
                                "to another authenticated user."
                            ),
                            embedding=[0.02] * 1536,
                        )
                    )

                    db.commit()

                    client = OpenAI(api_key=api_key)

                    audit = AuditService(
                        session_factory=audit_session_factory
                    )

                    workflow = SecureInvestigationWorkflow(
                        client=client,
                        model=model,
                        audit_service=audit,
                    )

                    request = (
                        "Investigate suspicious failed "
                        "login activity. Use the approved "
                        "read-only security analysis tools "
                        "and summarize supporting evidence."
                    )

                    result = await workflow.run(
                        db=db,
                        user_id=owner_id,
                        request=request,
                        events=[],
                        granted_permissions={
                            "security:read"
                        },
                        top_k=5,
                        document_id=document.id,
                    )

                    print(
                        "\nInvestigation status:",
                        result["status"],
                    )

                    print(
                        "Synthesis status:",
                        result.get("synthesis_status"),
                    )

                    assert result["status"] == "completed"
                    assert (
                        result["synthesis_status"]
                        == "completed"
                    )

                    investigation_id = result[
                        "investigation_id"
                    ]

                    assert investigation_id

                    # Verify that evidence belongs to
                    # the authenticated owner.
                    sources = result.get(
                        "evidence", {}
                    ).get("sources", [])

                    assert sources, (
                        "Expected owner-scoped evidence"
                    )

                    assert all(
                        source["document_id"]
                        == document.id
                        for source in sources
                    )

                    assert all(
                        source["document_id"]
                        != foreign_document.id
                        for source in sources
                    )

                    synthesis = result[
                        "evidence_synthesis"
                    ]

                    assert isinstance(synthesis, dict)

                    allowed_source_ids = {
                        source["chunk_id"]
                        for source in sources
                    }

                    assert set(
                        synthesis["source_ids"]
                    ).issubset(allowed_source_ids)

                    # Read actual persisted audit
                    # history from PostgreSQL.
                    history = audit.get_history(
                        investigation_id=investigation_id,
                        user_id=owner_id,
                    )

                    assert history is not None
                    assert (
                        history["investigation_id"]
                        == investigation_id
                    )
                    assert history["status"] == "completed"

                    event_types = [
                        event["event_type"]
                        for event in history["events"]
                    ]

                    assert "investigation_started" in event_types
                    assert "tool_executed" in event_types
                    assert "evidence_retrieved" in event_types
                    assert "evidence_synthesis" in event_types
                    assert "investigation_completed" in event_types

                    # Synthesis must be audited before
                    # final investigation completion.
                    assert event_types.index(
                        "evidence_synthesis"
                    ) < event_types.index(
                        "investigation_completed"
                    )

                    assert (
                        history["events"][-1]["event_type"]
                        == "investigation_completed"
                    )

                    # Audit history is user-scoped.
                    unauthorized_history = audit.get_history(
                        investigation_id=investigation_id,
                        user_id=other_user_id,
                    )

                    assert unauthorized_history is None

                    print(
                        "Audit events:",
                        event_types,
                    )

                    print(
                        "Live A3 verification: PASSED"
                    )

            finally:
                # Roll back the entire test transaction,
                # including audit records and test data.
                outer_transaction.rollback()

    finally:
        engine.dispose()


